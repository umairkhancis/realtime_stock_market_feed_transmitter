/// Resolves a destination, defaulting the port when only a host is given.
pub fn resolve(dest: &str) -> io::Result<SocketAddr> {
    let owned;
    let with_port = if dest.contains(':') {
        dest
    } else {
        owned = format!("{dest}:{DEFAULT_PORT}");
        &owned
    };
    with_port.to_socket_addrs()?.next().ok_or_else(|| {
        io::Error::new(
            io::ErrorKind::AddrNotAvailable,
            format!("{dest} resolved to no address"),
        )
    })
}

/// `data/feed.csv` -> `data/feed.symbols.csv`.
fn symbols_path(feed: &Path) -> PathBuf {
    let stem = feed
        .file_stem()
        .map(|s| s.to_string_lossy().into_owned())
        .unwrap_or_default();
    feed.with_file_name(format!("{stem}.symbols.csv"))
}

/// A very small `--key value` / `--key=value` parser.
///
/// Not a general argument library: it exists so the binary has no dependencies
/// and so an unrecognised flag is an error rather than a silent no-op.
struct Args {
    values: Vec<(String, Option<String>)>,
}

impl Args {
    fn parse(argv: &[String]) -> Result<Args, String> {
        let mut values = Vec::new();
        let mut i = 0;
        while i < argv.len() {
            let arg = &argv[i];
            let key = arg.strip_prefix("--").ok_or_else(|| {
                format!("expected an option starting with --, got {arg:?}\n\n{USAGE}")
            })?;
            match key.split_once('=') {
                Some((k, v)) => {
                    values.push((k.to_string(), Some(v.to_string())));
                    i += 1;
                }
                None => {
                    // A flag is bare if the next token is another option.
                    let next = argv.get(i + 1);
                    match next {
                        Some(v) if !v.starts_with("--") => {
                            values.push((key.to_string(), Some(v.clone())));
                            i += 2;
                        }
                        _ => {
                            values.push((key.to_string(), None));
                            i += 1;
                        }
                    }
                }
            }
        }
        Ok(Args { values })
    }

    fn get(&self, key: &str) -> Option<&str> {
        self.values
            .iter()
            .find(|(k, _)| k == key)
            .and_then(|(_, v)| v.as_deref())
    }

    fn has(&self, key: &str) -> bool {
        self.values.iter().any(|(k, _)| k == key)
    }

    fn parse_or<T: std::str::FromStr>(&self, key: &str, default: T) -> Result<T, String> {
        match self.get(key) {
            None => Ok(default),
            Some(v) => v
                .parse()
                .map_err(|_| format!("--{key} expects a number, got {v:?}")),
        }
    }

    fn market_config(&self) -> Result<MarketConfig, String> {
        let default = MarketConfig::default();
        Ok(MarketConfig {
            seed: self.parse_or("seed", default.seed)?,
            count: self.parse_or("count", DEFAULT_MESSAGE_COUNT)?,
            interval_nanos: self.parse_or("interval-nanos", DEFAULT_INTERVAL_NANOS)?,
        })
    }

    /// Either reads the feed from CSV or generates it. Generating is the
    /// default so the tool has no hidden dependency on a file existing; with
    /// the same seed and count the two are identical.
    fn load_messages(&self) -> Result<Vec<ItchMessage>, Box<dyn std::error::Error>> {
        match self.get("csv") {
            Some(path) => {
                let messages = read_feed(BufReader::new(File::open(path)?))?;
                println!("read {} messages from {path}", messages.len());
                Ok(messages)
            }
            None => {
                let config = self.market_config()?;
                println!(
                    "generating {} messages in memory, seed {:#018x} \
                     (identical to `gen --seed {} --count {}`)",
                    config.count, config.seed, config.seed, config.count
                );
                Ok(MarketSimulator::new(config).collect())
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn argv(s: &[&str]) -> Vec<String> {
        s.iter().map(|x| x.to_string()).collect()
    }

    #[test]
    fn args_accept_both_spellings() {
        let a = Args::parse(&argv(&["--count", "5", "--seed=7", "--quiet"])).unwrap();
        assert_eq!(a.get("count"), Some("5"));
        assert_eq!(a.get("seed"), Some("7"));
        assert!(a.has("quiet"));
        assert_eq!(a.get("quiet"), None);
        assert!(!a.has("nope"));
    }

    #[test]
    fn args_reject_a_stray_positional() {
        assert!(Args::parse(&argv(&["count", "5"])).is_err());
    }

    #[test]
    fn args_parse_numbers_and_report_bad_ones() {
        let a = Args::parse(&argv(&["--rate", "20000", "--count", "twelve"])).unwrap();
        assert_eq!(a.parse_or("rate", 1u64).unwrap(), 20_000);
        assert_eq!(a.parse_or("missing", 99u64).unwrap(), 99);
        assert!(a.parse_or("count", 1u64).is_err());
    }

    #[test]
    fn market_config_defaults_to_the_slice_2_numbers() {
        let cfg = Args::parse(&argv(&[])).unwrap().market_config().unwrap();
        assert_eq!(cfg.count, 100_000);
        assert_eq!(
            cfg.interval_nanos, 100_000,
            "100 µs = 10,000 messages/second"
        );
    }

    #[test]
    fn symbols_path_sits_beside_the_feed() {
        assert_eq!(
            symbols_path(Path::new("data/feed.csv")),
            Path::new("data/feed.symbols.csv")
        );
        assert_eq!(
            symbols_path(Path::new("run1.csv")),
            Path::new("run1.symbols.csv")
        );
    }

    #[test]
    fn resolve_supplies_the_default_port() {
        let a = resolve("127.0.0.1").unwrap();
        assert_eq!(a.port(), 9000);
        let b = resolve("127.0.0.1:1234").unwrap();
        assert_eq!(b.port(), 1234);
        assert!(resolve("not a host name at all").is_err());
    }

    /// The claim the usage text makes: the CSV and an in-memory generation with
    /// the same seed are the same feed.
    #[test]
    fn csv_and_in_memory_generation_agree() {
        let cfg = MarketConfig {
            count: 4_000,
            ..Default::default()
        };
        let generated: Vec<ItchMessage> = MarketSimulator::new(cfg).collect();
        let mut csv = Vec::new();
        write_feed(&mut csv, generated.iter().copied()).unwrap();
        assert_eq!(read_feed(csv.as_slice()).unwrap(), generated);
    }
}
